def normalize_locale(locale: str | None) -> str:
    return locale if locale in TRANSLATIONS else "de"


def translate(locale: str, key: str, **values: Any) -> str:
    lang = normalize_locale(locale)
    text = TRANSLATIONS[lang].get(key)
    if text is None:
        text = TRANSLATIONS["de"].get(key, key)
    return text.format(**values)


def format_money(cents: int | None, locale: str = "de") -> str:
    if cents is None:
        return "—"
    babel_locale = "de_DE" if normalize_locale(locale) == "de" else "en_GB"
    return babel_format_currency(cents / 100, "EUR", locale=babel_locale)


def format_date(value: date | None, locale: str = "de", format: str = "medium") -> str:
    if value is None:
        return "—"
    babel_locale = "de_DE" if normalize_locale(locale) == "de" else "en_GB"
    return babel_format_date(value, format=format, locale=babel_locale)


def format_datetime(value: datetime | None, locale: str = "de") -> str:
    if value is None:
        return "—"
    babel_locale = "de_DE" if normalize_locale(locale) == "de" else "en_GB"
    return babel_format_datetime(value, format="medium", locale=babel_locale)


def safe_markup(value: str) -> Markup:
    return Markup(value)


def missing_translation_keys() -> dict[str, set[str]]:
    all_keys = set().union(*(messages.keys() for messages in TRANSLATIONS.values()))
    return {locale: all_keys - set(messages) for locale, messages in TRANSLATIONS.items()}
